/** Explicit isolated-experiment reference input. Never a final layer or completed result. */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import sharp from 'sharp';
import { z } from 'zod';
import type { GenerationState } from '../server/generation.js';
import { placementPreview } from '../server/generation-placement.js';

export const parentImportScope = z.object({
  taskId: z.string().min(1), jobId: z.string().min(1), imageId: z.string().min(1),
  generationId: z.string().min(1), expectedWorkingHash: z.string().regex(/^[a-f0-9]{64}$/),
  expectedSourceHash: z.string().regex(/^[a-f0-9]{64}$/),
}).strict();
type Job = { id: string; taskId?: string; documentId: string; imageId: string; status: string;
  snapshot: { width: number; height: number } };
const digest = (b: Buffer | string) => crypto.createHash('sha256').update(b).digest('hex');
export async function captureParentSource(data: string, job: Job, state: GenerationState,
  sourcePath: string, raw: unknown, actualTaskId: string) {
  const scope = parentImportScope.parse(raw);
  if (scope.taskId !== actualTaskId || job.taskId !== actualTaskId || scope.jobId !== job.id ||
      scope.imageId !== job.imageId || job.status !== 'running')
    throw Error('父素材须来自当前已领取的同一实验任务；不能引用历史或其他对话。');
  const record = state.outputs.find(g => g.id === scope.generationId);
  const request = state.requests.find(q => q.id === record?.requestId);
  if (!record || !request || record.kind || record.derivedAlpha || record.derivedBackground ||
      record.receipt.tool !== 'image_gen' || record.isolationProblem || !record.placedPreviewPath ||
      (record.blendMode || 'normal') !== 'normal' || record.review?.status !== 'accepted' ||
      record.review.issues.length || !record.elements?.length ||
      record.elements.length !== request.elements.length ||
      record.elements.some((e, i) => e.name !== request.elements[i] || e.status !== 'matched'))
    throw Error('只允许已经逐项接受的真实普通生成父素材；失败、光效或派生结果不能成为子层参考。');
  if (record.workingHash !== scope.expectedWorkingHash ||
      JSON.stringify(record.sourceLayerIds) !== JSON.stringify(request.sourceLayerIds) ||
      JSON.stringify(record.frame) !== JSON.stringify(request.frame) ||
      record.receipt.prompt !== request.prompt ||
      JSON.stringify(record.receipt.referencePaths) !== JSON.stringify(request.referencePaths) ||
      request.referencePaths.length !== request.referenceHashes.length ||
      request.referencePaths.length === 0)
    throw Error('父素材与冻结请求/原件或提示引用不一致。');
  const realBase = fs.realpathSync(data), files = new Map<string, { path: string; sha256: string }>();
  function read(file: string, expected?: string) {
    const resolved = fs.realpathSync(file), relative = path.relative(realBase, resolved);
    if (!relative || relative.startsWith('..') || path.isAbsolute(relative))
      throw Error('父素材引用越过当前实验目录，不能使用生产文件或链接别名。');
    const bytes = fs.readFileSync(resolved), sha256 = digest(bytes);
    if (expected && sha256 !== expected) throw Error('父素材绑定文件已变化。');
    if (files.has(resolved) && files.get(resolved)!.sha256 !== sha256) throw Error('父素材读取期间变化。');
    files.set(resolved, { path: resolved, sha256 });
    return bytes;
  }
  read(sourcePath, scope.expectedSourceHash);
  read(record.originalPath, record.hash);
  const working = read(record.workingPath, record.workingHash);
  read(record.comparisonPath, record.comparisonHash);
  for (const [i, p] of request.referencePaths.entries()) read(p, request.referenceHashes[i]);
  const meta = await sharp(working).metadata(), canvas = job.snapshot;
  if (!meta.width || !meta.height || meta.width * meta.height > 1500000 ||
      canvas.width * canvas.height > 1500000 || canvas.width <= 0 || canvas.height <= 0 ||
      meta.width !== record.workingSize.width || meta.height !== record.workingSize.height ||
      record.backgroundPadding || !record.placementFrame ||
      Object.values(record.placementFrame).some(n => !Number.isFinite(n)) ||
      record.placementFrame.width <= 0 || record.placementFrame.height <= 0)
    throw Error('父素材完整文件/画幅或定位不符合150万像素参考预算。');
  // Reproduce the entire source-frame reference from true generated bytes; no original RGB is copied.
  const bytes = await placementPreview(working, record.placementFrame,
    { x: 0, y: 0, width: canvas.width, height: canvas.height }, canvas);
  const expected = await sharp(bytes).ensureAlpha().raw().toBuffer();
  const placed = read(record.placedPreviewPath);
  const actual = await sharp(placed).ensureAlpha().raw().toBuffer();
  if (!actual.equals(expected)) throw Error('父素材原位参考不再对应真实工作文件和定位。');
  const stateHash = digest(JSON.stringify(state)), jobHash = digest(JSON.stringify(job));
  function assertUnchanged(currentJob: Job, currentState: GenerationState) {
    if (digest(JSON.stringify(currentJob)) !== jobHash || digest(JSON.stringify(currentState)) !== stateHash)
      throw Error('父素材任务/审核/定位在引用期间发生变化，保留新导入但不得创建子层任务。');
    for (const f of files.values()) if (digest(fs.readFileSync(f.path)) !== f.sha256)
      throw Error('父素材文件在引用期间变化，不能继续子层任务。');
  }
  assertUnchanged(job, state);
  return { bytes, assertUnchanged, binding: { version: 1, ...scope, documentId: job.documentId,
    requestId: request.id, sourcePath, stateHash, jobHash, files: [...files.values()],
    referenceHash: digest(bytes), referenceSize: canvas, placementFrame: record.placementFrame,
    origin: 'accepted-generated-parent-reference' as const, finalMaterial: false,
    wholeGoalAccepted: false, nativeCanvasAncestryCreated: false } };
}
